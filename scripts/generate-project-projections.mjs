import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import process from "node:process";

const ROOT = process.cwd();
const SOURCE_PATH = join(ROOT, "content", "projects", "harness-source.json");
const PUBLICATION_PATH = join(ROOT, "content", "projects", "harness-publication.json");
const OUTPUT_PATH = join(ROOT, "content", "projects", "generated-harness.ts");

function fail(message) {
  throw new Error(`harness public projection: ${message}`);
}

function removedTerms(items) {
  const terms = new Set();
  for (const item of items || []) {
    for (const match of item.matchAll(/`([^`]+)`/g)) terms.add(match[1]);
    for (const phrase of [
      "Host-backed Runner", "TaskContract", "Assignment", "Host compatibility package",
      "Host dependency", "host CLI namespace", "cutover", "Codex/Hermes execution drivers",
    ]) {
      if (item.toLowerCase().includes(phrase.toLowerCase())) terms.add(phrase);
    }
  }
  return [...terms].filter((term) => term.length >= 5);
}

function allStrings(value, path = "root", result = []) {
  if (typeof value === "string") result.push({ path, value });
  else if (Array.isArray(value)) value.forEach((item, index) => allStrings(item, `${path}[${index}]`, result));
  else if (value && typeof value === "object") Object.entries(value).forEach(([key, item]) => allStrings(item, `${path}.${key}`, result));
  return result;
}

const source = JSON.parse(await readFile(SOURCE_PATH, "utf8"));
const publication = JSON.parse(await readFile(PUBLICATION_PATH, "utf8"));

if (source.schemaVersion !== 1 || publication.schemaVersion !== 1) fail("unsupported schema version");
if (!source.admission?.accepted) fail("captured source is not admitted");
if (source.project?.id !== publication.projectId) fail("project identity mismatch");
if (source.source?.revision !== publication.sourceRevision) fail("publication was not reviewed against captured source revision");
if (source.source?.publicSourceDigest !== publication.sourceDigest) fail("publication was not reviewed against captured public-source digest");
if (source.source?.statusDigest !== publication.statusDigest) fail("publication status anchor does not match captured status digest");
if (source.project?.publicProjection !== "ordivon-web") fail("owner did not target Ordivon Web");

// Removed concepts may still appear in explicit historical or boundary language. Reject them only
// when the publication asserts present capability/ownership/evidence using those retired terms.
const currentClaims = {
  boundarySummary: publication.boundary.summary,
  boundaryOwns: publication.boundary.owns,
  projectCapability: publication.project.capability,
  projectLatestProof: publication.project.latestProof,
  projectSummary: publication.project.summary,
  projectEvidence: publication.project.evidence,
};
const retired = removedTerms(source.candidate?.removed);
const contradictions = [];
for (const { path, value } of allStrings(currentClaims)) {
  for (const term of retired) {
    if (value.toLowerCase().includes(term.toLowerCase())) contradictions.push(`${path}: asserts retired ${term}`);
  }
}
if (contradictions.length) fail(contradictions.join("; "));

const boundary = {
  ...publication.boundary,
  updatedAt: source.source.updated,
};
const project = {
  ...publication.project,
  title: source.project.name,
  lifecycle: source.source.lifecycle,
  repository: source.project.repository,
  updatedAt: source.source.updated,
};
const receipt = {
  schemaVersion: 1,
  projectId: source.project.id,
  sourceRevision: source.source.revision,
  publicSourceDigest: source.source.publicSourceDigest,
  publicDocuments: source.source.documents.map(({ path, digest }) => ({ path, digest })),
  statusDocument: source.source.statusDocument,
  statusDigest: source.source.statusDigest,
  sourceUpdatedAt: source.source.updated,
  evidenceStatus: source.source.evidenceStatus,
  readiness: source.source.readiness,
};

const output = `// Generated by scripts/generate-project-projections.mjs. Do not edit.\nimport type { BoundaryDefinition, ProjectDefinition } from "../../lib/model/types";\n\nexport const harnessBoundary = ${JSON.stringify(boundary, null, 2)} as const satisfies BoundaryDefinition;\n\nexport const harnessProject = ${JSON.stringify(project, null, 2)} as const satisfies ProjectDefinition;\n\nexport const harnessProjectionReceipt = ${JSON.stringify(receipt, null, 2)} as const;\n`;
await writeFile(OUTPUT_PATH, output);
console.log(`project_projection=passed project=harness revision=${receipt.sourceRevision}`);
