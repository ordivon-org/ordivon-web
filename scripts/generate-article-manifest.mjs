import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import process from "node:process";
import { readArticleSources } from "./article-sources.mjs";

const ROOT = process.cwd();
const METADATA_OUTPUT = join(ROOT, "content", "articles", "generated-metadata.ts");
const MANIFEST_OUTPUT = join(ROOT, "content", "articles", "generated-manifest.ts");
const check = process.argv.includes("--check");

function componentName(slug) {
  return slug.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("") + "Article";
}

function metadataSource(articles) {
  const metadata = articles.map((article) => article.metadata);
  return `// Generated by scripts/generate-article-manifest.mjs. Do not edit.\nimport type { ArticleMetadata } from "./schema";\n\nexport const articleMetadata = ${JSON.stringify(metadata, null, 2)} as const satisfies readonly ArticleMetadata[];\n\nexport type ArticleSlug = (typeof articleMetadata)[number]["slug"];\n`;
}

function manifestSource(articles) {
  const imports = articles.map(({ file, metadata }) => `import ${componentName(metadata.slug)} from "./${file}";`).join("\n");
  const mappings = articles.map(({ metadata }) => `  "${metadata.slug}": ${componentName(metadata.slug)},`).join("\n");
  return `// Generated by scripts/generate-article-manifest.mjs. Do not edit.\nimport type { ComponentType } from "react";\n${imports}\nimport { articleMetadata, type ArticleSlug } from "./generated-metadata";\n\nconst articleComponents: Record<ArticleSlug, ComponentType> = {\n${mappings}\n};\n\nexport const articleManifest = articleMetadata.map((metadata) => ({ ...metadata, Content: articleComponents[metadata.slug] }));\n`;
}

async function sync(path, expected) {
  if (check) {
    const current = await readFile(path, "utf8").catch(() => "");
    if (current !== expected) throw new Error(`${path.replace(`${ROOT}/`, "")} is not synchronized with article MDX sources`);
  } else {
    await writeFile(path, expected);
  }
}

const articles = await readArticleSources();
await sync(METADATA_OUTPUT, metadataSource(articles));
await sync(MANIFEST_OUTPUT, manifestSource(articles));
console.log(`article_sources=${articles.length} mode=${check ? "check" : "write"}`);
